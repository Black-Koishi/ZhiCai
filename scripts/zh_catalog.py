def main():
    conn = sqlite3.connect(str(DB_PATH))
    for vid, name in VENDORS_ZH.items():
        conn.execute("UPDATE vendors SET name = ? WHERE id = ?", (name, vid))
    for iid, name in ITEMS_ZH.items():
        conn.execute("UPDATE items SET name = ? WHERE id = ?", (name, iid))
    conn.commit()

    v_updated = conn.execute(
        "SELECT COUNT(*) FROM vendors WHERE id IN (%s)"
        % ",".join(str(i) for i in VENDORS_ZH)
    ).fetchone()[0]
    i_updated = conn.execute(
        "SELECT COUNT(*) FROM items WHERE id IN (%s)"
        % ",".join(str(i) for i in ITEMS_ZH)
    ).fetchone()[0]
    conn.close()

    print(f"已翻译供应商 {v_updated} 家、物料 {i_updated} 个为中文。")


if __name__ == "__main__":
    main()
